#!/usr/bin/env python3
"""Writes every list of supported watches from app/manifest.xml and the device facts.

The manifest says which products ship; tools/ui/devices/11-devdata.js (generated by devdata.py from the
SDK's device files, and committed) says what each one is. Everything else that names the watches is
written from those two, between marker lines, so adding a watch is a manifest line and two generator runs:

  app/monkey.jungle          per product: the map left out where MapView is missing, the launcher icon
                             folder where the icon is not 40 px (app/resources-launcher-<size>/)
  app/manifest.xml           the product block of the header comment
  README.md                  the "Supported watches" table
  docs/adding-a-watch.md     the screen families (section 1) and the "Currently supported" table
  docs/store-listing.md      the products marker and the list of watches under "Requirements"
  docs/design/style-guide.md the screens table (section 5)

Watch names come from each device file's display name ("fēnix® 7X / tactix® 7 / ..." gives "fēnix 7X",
also "tactix 7", ...); NAMES below overrides the few where that reads badly or where the store lists more
models than the device file. Needs no SDK, so CI checks it (tools/checks.py, "Generated device lists").

Usage:
  python3 tools/devicelists.py           rewrite the lists
  python3 tools/devicelists.py --check   fail if any list differs from a fresh run
"""
from __future__ import annotations

import json
import pathlib
import re
import sys
import textwrap

ROOT = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "app" / "manifest.xml"
DEVDATA = ROOT / "tools" / "ui" / "devices" / "11-devdata.js"
DEFAULT_ICON = 40   # resources/drawables/launcher_icon.svg

# Name and the models one product id also covers, where the device file's display name does not give
# them well. The store's Compatible Devices list is the source for the extra models of the fēnix 7 Pro
# and fēnix 7.
NAMES = {
    "fenix7pro": ("fēnix 7 Pro", ["Solar", "Sapphire Solar", "Sapphire Dual Power"]),
    "fenix7": ("fēnix 7", ["quatix 7", "Sapphire Dual Power"]),
    "fenix7pronowifi": ("fēnix 7 Pro Solar Edition (no Wi-Fi)", []),
    "fenix7xpronowifi": ("fēnix 7X Pro Solar Edition (no Wi-Fi)", []),
    "fr955": ("Forerunner 955", ["955 Solar"]),
    "fr255s": ("Forerunner 255S", []),
    "fr255sm": ("Forerunner 255S Music", []),
    "marq2": ("MARQ (Gen 2)", ["Athlete", "Adventurer", "Captain", "Golfer", "Carbon Edition",
                               "Commander Carbon Edition"]),
    "fenix847mm": ("fēnix 8 47mm and 51mm", ["tactix 8", "quatix 8"]),
    "fenix8pro47mm": ("fēnix 8 Pro 47mm and 51mm", ["MicroLED", "quatix 8 Pro"]),
    "fenix947mm": ("fēnix 9 47mm and 51mm", []),
    "epix2pro51mm": ("epix Pro (Gen 2) 51mm", ["D2 Mach 1 Pro", "tactix 7 AMOLED Edition"]),
}
INPUT = {  # README / manifest wording per input profile
    "A": "Five buttons, touch", "A0": "Five buttons", "B": "Touch, MENU is hold BACK",
    "C": "Touch, no MENU: swipe left",
}
PROFILE_ORDER = ["A", "A0", "B", "C"]


# ------------------------------------------------------------------ inputs
def products() -> list[str]:
    return re.findall(r'<iq:product\s+id="([^"]+)"', MANIFEST.read_text(encoding="utf-8"))


def dev_data() -> dict:
    text = DEVDATA.read_text(encoding="utf-8")
    m = re.search(r"\bconst\s+DEV_DATA\s*=\s*", text)
    if not m:
        sys.exit(f"ERROR: {DEVDATA.relative_to(ROOT)} has no DEV_DATA; run tools/ui/devices/devdata.py")
    return json.JSONDecoder().raw_decode(text, m.end())[0]


def name_of(pid: str, d: dict) -> tuple[str, list[str]]:
    if pid in NAMES:
        return NAMES[pid]
    parts = [re.sub(r"\s+", " ", p.replace("®", "").replace("™", "")).strip() for p in d["name"].split(" / ")]
    return parts[0], parts[1:]


def screen(d: dict) -> str:
    shape = f"{d['w']}×{d['h']} rectangle" if d["shape"] == "rectangle" else f"{d['w']} round"
    return f"{shape}, {'MIP' if d['displayType'] == 'mip' else 'AMOLED'}"


def ordered(pids: list[str], data: dict) -> list[str]:
    """Grouped by screen: MIP before AMOLED, round before rectangle, by size, then input profile,
    then manifest order."""
    key = lambda p: (data[p]["displayType"] != "mip", data[p]["shape"] != "round", data[p]["w"], data[p]["h"],
                     PROFILE_ORDER.index(data[p]["profile"]), pids.index(p))
    return sorted(pids, key=key)


def words(items: list[str]) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


# ------------------------------------------------------------------ the lists
def readme(pids, data) -> str:
    rows = ["| Watch | Device id | Screen | Input | Map | Connect IQ |", "|---|---|---|---|---|---|"]
    for p in ordered(pids, data):
        d, (name, also) = data[p], name_of(p, data[p])
        watch = name + (", incl. " + ", ".join(also) if also else "")
        rows.append(f"| {watch} | `{p}` | {screen(d)} | {INPUT[d['profile']]} | "
                    f"{'Yes' if d['mapView'] else 'No'} | {d['ciq']} |")
    return "\n".join(rows)


def guide(pids, data) -> str:
    rows = ["| Device id | Watch | Screen | Input | Map |", "|---|---|---|---|---|"]
    for p in ordered(pids, data):
        d, (name, also) = data[p], name_of(p, data[p])
        watch = ", ".join([name] + also)
        if d["budget"]["watchApp"] < 786_432:
            watch += f" (watch-app budget {d['budget']['watchApp']:,} B)"
        if tuple(int(x) for x in d["ciq"].split(".")) < (5, 2):
            watch += f" (Connect IQ {d['ciq']})"
        rows.append(f"| `{p}` | {watch} | {screen(d)} | {d['profile']} | {'yes' if d['mapView'] else 'no'} |")
    return "\n".join(rows)


def by_family(pids, data) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for p in ordered(pids, data):
        out.setdefault(data[p]["family"], []).append(p)
    return out


def families(pids, data) -> str:
    rows = ["| `deviceFamily` | Screen | Watches today |", "|---|---|---|"]
    for fam, group in by_family(pids, data).items():
        d = data[group[0]]
        shape = f"{d['w']}×{d['h']} rounded rectangle" if d["shape"] == "rectangle" else f"{d['w']} round"
        rows.append(f"| `{fam}` | {shape}, {'MIP' if d['displayType'] == 'mip' else 'AMOLED'} | "
                    f"{', '.join(name_of(p, data[p])[0] for p in group)} |")
    return "\n".join(rows)


def style_screens(pids, data) -> str:
    rows = ["| Screen | Watches | Input profile ([section 7](#7-interaction)) |", "|---|---|---|"]
    for group in by_family(pids, data).values():
        d = data[group[0]]
        shape = f"Rectangle {d['w']}×{d['h']}" if d["shape"] == "rectangle" else f"Round {d['w']}"
        profs: dict[str, list[str]] = {}
        for p in group:
            profs.setdefault(data[p]["profile"], []).append(name_of(p, data[p])[0])
        order = [k for k in PROFILE_ORDER if k in profs]
        rows.append(f"| {shape}, {'MIP' if d['displayType'] == 'mip' else 'AMOLED'} | "
                    f"{'; '.join(', '.join(profs[k]) for k in order)} | {'; '.join(order)} |")
    return "\n".join(rows)


def store(pids, data) -> str:
    marker = "; ".join(f'{p}="{name_of(p, data[p])[0]}"' for p in pids)
    lowest = min((data[p]["ciq"] for p in pids), key=lambda v: tuple(int(x) for x in v.split(".")))
    out = [f"<!-- products: {marker} -->", "",
           f"- One of these Garmin watches, with Connect IQ {'.'.join(lowest.split('.')[:2])} or later:"]
    groups: dict[tuple, list[str]] = {}
    for p in ordered(pids, data):
        d = data[p]
        groups.setdefault((d["displayType"], d["shape"], d["w"], d["h"]), []).append(p)
    for group in groups.values():
        names = []
        for p in group:
            name, also = name_of(p, data[p])
            names.append(name + (f" (also {words(also)})" if also else ""))
        out += textwrap.wrap(", ".join(names), 76, initial_indent="  - ", subsequent_indent="    ",
                             break_on_hyphens=False)
    return "\n".join(out)


def manifest_block(pids, data) -> str:
    out = []
    for p in ordered(pids, data):
        d, (name, also) = data[p], name_of(p, data[p])
        text = (name + (f"; also {', '.join(also)}" if also else "") + f". {screen(d)}, input {d['profile']}"
                + ("" if d["mapView"] else ", no map") + f", Connect IQ {d['ciq']}.")
        out += textwrap.wrap(text, 74, initial_indent=f"      {p:<19} " if len(p) < 20 else f"      {p} ",
                             subsequent_indent=" " * 26, break_on_hyphens=False)
    return "\n".join(out)


def jungle(pids, data) -> str:
    out = []
    for p in pids:
        d = data[p]
        if not d["mapView"]:
            out.append(f"{p}.excludeAnnotations = map")
        if d["launcher"] != DEFAULT_ICON:
            out.append(f"{p}.resourcePath = $({p}.resourcePath);resources-launcher-{d['launcher']}")
    return "\n".join(out)


# ------------------------------------------------------------------ files and markers
# (file, begin marker, end marker, generator). The markers stay in the file; only the lines between change.
TARGETS = [
    ("app/monkey.jungle", "# devicelists begin", "# devicelists end", jungle),
    ("app/manifest.xml", "    [devicelists begin]", "    [devicelists end]", manifest_block),
    ("README.md", "<!-- devicelists begin -->", "<!-- devicelists end -->", readme),
    ("docs/adding-a-watch.md", "<!-- devicelists families begin -->", "<!-- devicelists families end -->", families),
    ("docs/adding-a-watch.md", "<!-- devicelists begin -->", "<!-- devicelists end -->", guide),
    ("docs/design/style-guide.md", "<!-- devicelists begin -->", "<!-- devicelists end -->", style_screens),
    ("docs/store-listing.md", "<!-- devicelists begin -->", "<!-- devicelists end -->", store),
]


def render() -> dict[str, str]:
    """Every target file's text with fresh lists, keyed by relative path."""
    pids, data = products(), dev_data()
    missing = [p for p in pids if p not in data]
    if missing:
        raise ValueError(f"not in 11-devdata.js: {', '.join(missing)}; run tools/ui/devices/devdata.py")
    out = {}
    for rel, begin, end, gen in TARGETS:
        text = out.get(rel) or (ROOT / rel).read_text(encoding="utf-8")
        i, j = text.find(begin + "\n"), text.find("\n" + end)
        if i < 0 or j < i:
            raise ValueError(f"{rel} has no '{begin.strip()}' ... '{end.strip()}' lines")
        out[rel] = text[:i + len(begin) + 1] + gen(pids, data) + text[j:]
    return out


def stale() -> list[str]:
    """What differs from a fresh run, plus launcher folders the jungle names but that do not exist."""
    bad = [f"{rel} is out of date; run tools/devicelists.py"
           for rel, text in render().items() if (ROOT / rel).read_text(encoding="utf-8") != text]
    for size in sorted({d["launcher"] for d in dev_data().values()} - {DEFAULT_ICON}):
        if not (ROOT / f"app/resources-launcher-{size}/drawables/launcher_icon.svg").is_file():
            bad.append(f"app/resources-launcher-{size}/ is missing: copy another resources-launcher-* "
                       f"folder and set its size to {size}")
    return bad


def main():
    if "--check" in sys.argv[1:]:
        bad = stale()
        for b in bad:
            print(f"ERROR: {b}", file=sys.stderr)
        if bad:
            sys.exit(1)
        print("the device lists match app/manifest.xml and the device facts")
        return
    for rel, text in render().items():
        if (ROOT / rel).read_text(encoding="utf-8") != text:
            (ROOT / rel).write_text(text, encoding="utf-8")
            print(f"wrote {rel}")


if __name__ == "__main__":
    main()
